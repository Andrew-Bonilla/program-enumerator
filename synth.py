"""
Enumerative program synthesizer for a tiny arithmetic DSL.

    E ::= x | y | 0 | 1 | 2 | + E E | - E E | * E E

Programs are written in Polish (prefix) notation, e.g. "- * x x y" means x*x - y.
Given input/output examples (x, y, out), we enumerate programs in order of
increasing size (number of tokens) and return the first one that matches
every example.

Approach: bottom-up enumeration.
  * bank[n] holds every program of size n we have kept so far.
  * Size-1 programs are the terminals.
  * A size-n program is "op L R" where size(L) + size(R) = n - 1.
    So we build size n by combining banks we already have.
  * Note every program has odd size (1, 3, 5, ...), since each operator
    adds 1 token and one extra subtree.

Optimization: observational equivalence pruning.
  We only care about a program's behavior on the given examples, so we
  represent each program by its output vector (one value per example).
  If two programs produce the same vector, they are interchangeable as
  subterms, so we keep only the first (smallest) one. This collapses things
  like "+ x y" vs "+ y x" or "* x 1" vs "x" and shrinks the search a lot.
  It never makes us miss a solution or return a bigger one than necessary.
"""

import sys

TERMINALS = ["x", "y", "0", "1", "2"]
OPERATORS = {
    "+": lambda a, b: a + b,
    "-": lambda a, b: a - b,
    "*": lambda a, b: a * b,
}


def terminal_values(tok, examples):
    """Output vector of a terminal across all examples."""
    if tok == "x":
        return tuple(x for x, _, _ in examples)
    if tok == "y":
        return tuple(y for _, y, _ in examples)
    return tuple(int(tok) for _ in examples)


# Number of candidate programs generated by the last synthesize() call
# (counts pruned ones too). Matches the "programs enumerated" column in the answer key.
last_count = 0


def synthesize(examples, max_size=9, prune=True):
    """
    examples: list of (x, y, out) integer tuples.
    Returns the first program (string) of minimal size that satisfies all
    examples, or None if nothing up to max_size works.
    """
    target = tuple(out for _, _, out in examples)

    # bank[size] = list of (program_string, output_vector)
    bank = {}
    seen = set()  # output vectors already represented (for pruning)

    global last_count
    last_count = 0

    def add(size, prog, vals):
        """Store a program; return True if it solves the problem."""
        global last_count
        last_count += 1
        if prune:
            if vals in seen:
                return False
            seen.add(vals)
        bank.setdefault(size, []).append((prog, vals))
        return vals == target

    # Size 1: terminals.
    for tok in TERMINALS:
        if add(1, tok, terminal_values(tok, examples)):
            return tok

    # Size n >= 3: "op L R" with size(L) + size(R) = n - 1.
    for size in range(3, max_size + 1, 2):
        for op, fn in OPERATORS.items():
            for left_size in range(1, size - 1, 2):
                right_size = size - 1 - left_size
                for lprog, lvals in bank.get(left_size, []):
                    for rprog, rvals in bank.get(right_size, []):
                        vals = tuple(fn(a, b) for a, b in zip(lvals, rvals))
                        prog = f"{op} {lprog} {rprog}"
                        if add(size, prog, vals):
                            return prog
    return None


# ---------- helpers for checking / running ----------

def evaluate(prog, x, y):
    """Evaluate a Polish-notation program string on inputs x, y."""
    tokens = prog.split()
    pos = 0

    def parse():
        nonlocal pos
        tok = tokens[pos]
        pos += 1
        if tok in OPERATORS:
            a = parse()
            b = parse()
            return OPERATORS[tok](a, b)
        if tok == "x":
            return x
        if tok == "y":
            return y
        return int(tok)

    return parse()


def parse_examples(text):
    """Parse lines like '1, 2, 3' into [(1, 2, 3), ...]. Blank lines and # comments skipped."""
    examples = []
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        a, b, c = (int(t) for t in line.replace(",", " ").split())
        examples.append((a, b, c))
    return examples


if __name__ == "__main__":
    # Usage: python synth.py examples.txt     (or pipe examples on stdin)
    text = open(sys.argv[1]).read() if len(sys.argv) > 1 else sys.stdin.read()
    exs = parse_examples(text)
    result = synthesize(exs)
    print(result if result is not None else "None (no program up to size 9)")
    print(f"({last_count} programs enumerated)")